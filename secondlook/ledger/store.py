"""LedgerStore: the one swap point between SQLite (local) and Cosmos DB (design §2.3)."""
from __future__ import annotations

from typing import Any, Protocol

from pydantic import BaseModel

from ..contracts.events import Event


class StoredEvent(BaseModel):
    event: Event
    match_ms: int
    arrival_order: int | None = None
    arrival_match_ms: int | None = None
    status: str = "active"  # active | corrected | void
    corrected_by: str | None = None
    rev: int = 0


class Revision(BaseModel):
    rev: int
    kind: str  # append | late | correction | gap
    event_id: str | None = None
    at_match_ms: int | None = None


class Gap(BaseModel):
    from_seq: int
    to_seq: int
    opened_rev: int
    closed_rev: int | None = None


# kinds accepted by put/get/set_status
KINDS = ("moment", "candidate", "claim", "verdict", "story", "viewer_output", "overlay",
         "viewer_profile")


class LedgerStore(Protocol):
    match_id: str

    # revisions and events
    def current_rev(self) -> int: ...
    def next_rev(self, kind: str, event_id: str | None = None, at_match_ms: int = 0) -> int: ...
    def revisions(self) -> list[Revision]: ...
    def has_event(self, event_id: str) -> bool: ...
    def append_event(self, ev: StoredEvent) -> None: ...
    def apply_correction(self, target_id: str, status: str, corrected_by: str | None,
                         rev: int) -> None: ...
    def get_event(self, event_id: str, as_of_rev: int | None = None) -> StoredEvent | None: ...
    def get_events(self, from_ms: int | None = None, to_ms: int | None = None,
                   types: list[str] | None = None, team_id: str | None = None,
                   player_id: str | None = None, as_of_rev: int | None = None,
                   statuses: tuple[str, ...] = ("active",)) -> list[StoredEvent]: ...
    # feed health
    def open_gap(self, from_seq: int, to_seq: int, rev: int, at_ms: int) -> None: ...
    def close_gap(self, seq: int, rev: int) -> bool: ...
    def gaps(self, open_only: bool = False) -> list[Gap]: ...
    def bump_stat(self, name: str, by: int = 1) -> None: ...
    def stat(self, name: str) -> int: ...
    # derived rows
    def put(self, kind: str, model: BaseModel, **cols: Any) -> None: ...
    def get(self, kind: str, id: str) -> BaseModel | None: ...
    def list_kind(self, kind: str, /, **filters: Any) -> list[BaseModel]: ...
    def set_status(self, kind: str, id: str, status: str, **fields: Any) -> None: ...
    def get_status(self, kind: str, id: str) -> str | None: ...
    def batch_set_status(self, updates: list[tuple[str, str, str, dict]]) -> None: ...
    # dependency graph
    def add_deps(self, edges: list[tuple[str, str, str, str]]) -> None: ...
    def children(self, kind: str, id: str) -> list[tuple[str, str]]: ...
    def parents(self, kind: str, id: str) -> list[tuple[str, str]]: ...
    def add_claim_event_deps(self, claim_id: str, event_ids: list[str]) -> None: ...
    def add_claim_window_dep(self, claim_id: str, team_id: str | None, event_types: list[str],
                             from_ms: int, to_ms: int) -> None: ...
    def claims_touching(self, event_ids: list[str],
                        points: list[tuple[str | None, str, int]]) -> list[str]: ...
    def overlays_since(self, cursor: int, profile_id: str | None = None
                       ) -> list[tuple[int, BaseModel]]: ...
